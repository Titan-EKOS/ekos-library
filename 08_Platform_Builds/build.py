"""Generate every platform build from the masters in 03_Skills, 04_Agents and 05_QC_Rules.

  python build.py              lint + build into out/, update manifest.json and README index
  python build.py --check      rebuild in memory; fail if out/, manifest or README index drift
  python build.py --install    build, then copy to ~/.claude/skills, ~/.codex/AGENTS.md, ~/.gemini/GEMINI.md
  python build.py --lint       lint only

Never hand-edit anything in out/. Change the master, then rebuild.
Output is deterministic (no timestamps) so --check can compare bytes.
"""
from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import re
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT / "09_Server"))

import yaml  # noqa: E402

from library_server.core import Library, parse_frontmatter  # noqa: E402

OUT = HERE / "out"
MANIFEST = HERE / "manifest.json"
README = ROOT / "README.md"
IDX_START, IDX_END = "<!-- INDEX:START -->", "<!-- INDEX:END -->"
GEN = "GENERATED by 08_Platform_Builds/build.py from {src} v{ver}. Do not edit; change the master and rebuild."
AGENTS_MD_LIMIT = 30000          # stay under the Codex default project-doc cap (32 KiB)
CLAUDE_NAME_RE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")


# ---------------------------------------------------------------- loading
class Master:
    def __init__(self, kind: str, folder: Path, meta: dict, body: str):
        self.kind, self.folder, self.meta, self.body = kind, folder, meta, body

    @property
    def name(self) -> str:
        return str(self.meta.get("name", self.folder.name))

    @property
    def version(self) -> str:
        return str(self.meta.get("version", "0.0.0"))

    @property
    def status(self) -> str:
        return str(self.meta.get("status", "active"))

    @property
    def src(self) -> str:
        return self.folder.relative_to(ROOT).as_posix()

    def resources(self) -> list[Path]:
        main = "SKILL.md" if self.kind == "skill" else "AGENT.md"
        return sorted(p for p in self.folder.rglob("*") if p.is_file() and p.name != main)


def load(kind: str) -> list[Master]:
    folder, fname = ("03_Skills", "SKILL.md") if kind == "skill" else ("04_Agents", "AGENT.md")
    out = []
    for d in sorted((ROOT / folder).iterdir()):
        f = d / fname
        if d.is_dir() and not d.name.startswith("_") and f.exists():
            meta, body = parse_frontmatter(f.read_text(encoding="utf-8"))
            out.append(Master(kind, d, meta, body))
    return out


# ---------------------------------------------------------------- lint
def _strip_unlinted(text: str) -> str:
    text = re.sub(r"<!--\s*lint-off\s*-->.*?<!--\s*lint-on\s*-->", "", text, flags=re.S)
    return re.sub(r"```.*?```", "", text, flags=re.S)


def lint(cfg: dict, skills: list[Master], agents: list[Master]) -> tuple[list[str], list[str]]:
    errs, warns = [], []
    skill_names = {s.name for s in skills}
    banned = [w.lower() for w in cfg["lint"]["banned_words"]]
    ai_terms = [w.lower() for w in cfg["lint"]["ai_terms"]]
    for m in skills + agents:
        req = cfg[m.kind]["required_frontmatter"]
        miss = [k for k in req if k not in m.meta]
        if miss:
            errs.append(f"{m.src}: missing frontmatter {miss}")
        if m.status not in cfg[m.kind]["status_values"]:
            errs.append(f"{m.src}: status '{m.status}' not in {cfg[m.kind]['status_values']}")
        if m.name != m.folder.name:
            errs.append(f"{m.src}: name '{m.name}' must match folder name")
        if m.kind == "skill":
            if not CLAUDE_NAME_RE.match(m.name) or len(m.name) > 64 or \
                    "claude" in m.name or "anthropic" in m.name:
                errs.append(f"{m.src}: name must be kebab-case, <=64 chars, "
                            "without 'claude'/'anthropic'")
            if len(str(m.meta.get("description", ""))) > 1024:
                errs.append(f"{m.src}: description over 1024 chars")
        if m.kind == "agent":
            for s in m.meta.get("skills") or []:
                if s not in skill_names:
                    errs.append(f"{m.src}: calls unknown skill '{s}'")
        low = _strip_unlinted(m.body).lower()
        for w in banned:
            if re.search(r"\b" + re.escape(w) + r"\b", low):
                warns.append(f"{m.src}: banned word '{w}'")
        for p in m.resources():
            rel = p.relative_to(m.folder).as_posix()
            if rel.startswith("templates/") and p.suffix.lower() in (".md", ".txt", ".html", ".csv"):
                t = " " + p.read_text(encoding="utf-8", errors="ignore").lower() + " "
                for w in ai_terms:
                    padded = w != w.strip()
                    hit = (w in t) if padded else re.search(r"\b" + re.escape(w) + r"\b", t)
                    if hit:
                        errs.append(f"{m.src}/{rel}: deliverable template contains '{w.strip()}'")
    return errs, warns


# ---------------------------------------------------------------- render
def _fm(d: dict) -> str:
    return "---\n" + yaml.safe_dump(d, sort_keys=False, allow_unicode=True, width=10000) + "---\n"


def _one_line(s) -> str:
    return " ".join(str(s or "").split())


def _skill_rows(skills):
    rows = ["| Skill | Version | Function | Jurisdiction | Use when |", "|---|---|---|---|---|"]
    for s in skills:
        rows.append(f"| {s.name} | {s.version} | {_one_line(s.meta.get('function'))} | "
                    f"{_one_line(s.meta.get('jurisdiction'))} | {_one_line(s.meta.get('description'))} |")
    return "\n".join(rows) if skills else "_No active skills yet._"


def _agent_rows(agents):
    rows = ["| Agent | Version | Calls skills | Role |", "|---|---|---|---|"]
    for a in agents:
        rows.append(f"| {a.name} | {a.version} | {', '.join(a.meta.get('skills') or [])} | "
                    f"{_one_line(a.meta.get('description'))} |")
    return "\n".join(rows) if agents else "_No active agents yet._"


def _qc_lines(rules):
    return "\n".join(f"- **{r.get('id')}** ({_one_line(r.get('scope', 'all'))}): {_one_line(r.get('rule'))}"
                     for r in rules) or "_No QC rules yet._"


def render_index_doc(cfg, skills, agents, rules, platform: str) -> str:
    head = f"<!-- {GEN.format(src='03_Skills, 04_Agents, 05_QC_Rules', ver=cfg['schema_version'])} -->\n"
    body = f"""# EKOS Library - standing instructions ({platform})

{_one_line(cfg['standing_instruction'])}

## How to reach the library
- MCP server `ekos-library` (stdio): tools `list_skills(filter)`, `get_skill(name)`,
  `list_agents()`, `get_agent(name)`, `get_qc_rules(scope)`, `add_card(card, source_ai, project)`,
  `log_lesson(project, text, evidence, source_ai)`.
- Without MCP: `D:\\EKOS\\Library\\09_Server\\.venv\\Scripts\\python.exe D:\\EKOS\\Library\\09_Server\\library_cli.py get-skill <name>` and
  `... log-lesson --project <job no> --source-ai {platform.lower()} --text "..." --evidence "<path>"`.
- Use `source_ai: {platform.lower()}` and the job number as `project`.

## Rules that always apply
- Get the full skill text with `get_skill` before starting the work it covers.
- Lesson cards hold lessons and file paths only. No client documents, no client data, no client names (use the job number).
- Anything that can reach a deliverable carries no AI wording and no AI tool names.
- Skills and agents are read-only. Propose changes through cards; JCO approves every change.

## Skills
{_skill_rows(skills)}

## Agents
{_agent_rows(agents)}
"""
    qc = f"\n## QC rules (summary; full text via get_qc_rules)\n{_qc_lines(rules)}\n"
    if len((head + body + qc).encode()) > AGENTS_MD_LIMIT:
        qc = "\n## QC rules\nToo many to list here. Call `get_qc_rules(scope)`.\n"
    return head + body + qc


def render_claude_skill(s: Master) -> str:
    fm = _fm({"name": s.name, "description": _one_line(s.meta.get("description"))})
    return fm + f"\n<!-- {GEN.format(src=s.src, ver=s.version)} -->\n" + s.body.lstrip("\n")


def render_local(cfg, agent: Master | None, skills_by_name: dict, skills, agents) -> str:
    cap = int(cfg["build"]["local_prompt_max_chars"])
    parts = [f"# {GEN.format(src=agent.src if agent else 'library index', ver=agent.version if agent else cfg['schema_version'])}",
             f"Standing instruction: {_one_line(cfg['standing_instruction'])}",
             "To log a lesson, run: D:\\EKOS\\Library\\09_Server\\.venv\\Scripts\\python.exe D:\\EKOS\\Library\\09_Server\\library_cli.py log-lesson "
             "--project <job no> --source-ai local:<model> --text \"...\" --evidence \"<path>\"",
             "Cards hold lessons and file paths only. No client data. No AI wording in deliverables."]
    if agent is None:
        parts += ["## Skills", _skill_rows(skills), "## Agents", _agent_rows(agents)]
    else:
        parts += ["## Agent definition", agent.body.strip()]
        for sn in agent.meta.get("skills") or []:
            s = skills_by_name.get(sn)
            if s:
                parts += [f"## Skill: {s.name} v{s.version}", s.body.strip()]
    text = "\n\n".join(parts) + "\n"
    if len(text) > cap:
        note = f"\n\n[Truncated at {cap} chars. Fetch full skills with library_cli.py get-skill <name>.]\n"
        text = text[: cap - len(note)] + note
    return text


def render_modelfile(cfg, agent: Master, prompt: str) -> str:
    base = cfg["build"]["local_base_model"]
    return (f"# {GEN.format(src=agent.src, ver=agent.version)}\nFROM {base}\n"
            f'SYSTEM """\n{prompt.replace(chr(34) * 3, chr(39) * 3)}"""\n')


def render_readme_index(skills, agents) -> str:
    rows = ["| Kind | Name | Version | Status | Replaces | Description |", "|---|---|---|---|---|---|"]
    for m in skills + agents:
        rows.append(f"| {m.kind} | {m.name} | {m.version} | {m.status} | "
                    f"{_one_line(m.meta.get('replaces', '-'))} | {_one_line(m.meta.get('description'))} |")
    table = "\n".join(rows) if (skills or agents) else "_No skills or agents built yet._"
    return f"{IDX_START}\n{table}\n{IDX_END}"


# ---------------------------------------------------------------- build
def build_files(cfg) -> tuple[dict[str, bytes], list[str], list[str], str]:
    all_skills, all_agents = load("skill"), load("agent")
    errs, warns = lint(cfg, all_skills, all_agents)
    keep = {"active", "draft"} if cfg["build"].get("include_drafts") else {"active"}
    skills = [s for s in all_skills if s.status in keep]
    agents = [a for a in all_agents if a.status in keep]
    rules = Library(ROOT, commit=False).get_qc_rules("all")
    by_name = {s.name: s for s in skills}

    files: dict[str, bytes] = {}
    for s in skills:
        files[f"claude/{s.name}/SKILL.md"] = render_claude_skill(s).encode()
        for p in s.resources():
            files[f"claude/{s.name}/{p.relative_to(s.folder).as_posix()}"] = p.read_bytes()
    files["AGENTS.md"] = render_index_doc(cfg, skills, agents, rules, "Codex").encode()
    files["GEMINI.md"] = render_index_doc(cfg, skills, agents, rules, "Gemini").encode()
    files["local/_library.txt"] = render_local(cfg, None, by_name, skills, agents).encode()
    for a in agents:
        prompt = render_local(cfg, a, by_name, skills, agents)
        files[f"local/{a.name}.txt"] = prompt.encode()
        if cfg["build"].get("local_base_model"):
            files[f"local/{a.name}.Modelfile"] = render_modelfile(cfg, a, prompt).encode()
    files = {k: v.replace(b"\r\n", b"\n") if not k.endswith((".png", ".jpg", ".pdf", ".xlsx", ".docx")) else v
             for k, v in files.items()}
    return files, errs, warns, render_readme_index(all_skills, all_agents)


def manifest_for(files: dict[str, bytes]) -> str:
    sources = {}
    for m in load("skill") + load("agent"):
        sources[m.src] = m.version
    data = {"files": {k: hashlib.sha256(v).hexdigest() for k, v in sorted(files.items())},
            "sources": dict(sorted(sources.items()))}
    return json.dumps(data, indent=2) + "\n"


def current_out() -> dict[str, bytes]:
    if not OUT.exists():
        return {}
    return {p.relative_to(OUT).as_posix(): p.read_bytes()
            for p in OUT.rglob("*") if p.is_file() and p.name != ".gitkeep"}


def update_readme(index: str, write: bool) -> bool:
    text = README.read_text(encoding="utf-8") if README.exists() else ""
    if IDX_START not in text:
        return True
    new = re.sub(re.escape(IDX_START) + r".*?" + re.escape(IDX_END), lambda _: index, text, flags=re.S)
    if write and new != text:
        README.write_text(new, encoding="utf-8", newline="\n")
    return new == text


def install(files: dict[str, bytes], force: bool) -> None:
    home = Path.home()
    stamp = dt.datetime.now().strftime("%Y%m%d")
    skills_dir = home / ".claude" / "skills"
    names = sorted({k.split("/")[1] for k in files if k.startswith("claude/")})
    for n in names:
        dest = skills_dir / n
        main = dest / "SKILL.md"
        if dest.exists():
            generated = main.exists() and "GENERATED by 08_Platform_Builds" in main.read_text(
                encoding="utf-8", errors="ignore")
            if not generated and not force:
                print(f"skip {dest} (hand-made skill exists; rerun with --force to replace, backup kept)")
                continue
            if not generated:
                shutil.copytree(dest, dest.with_name(f"{n}.bak_{stamp}"), dirs_exist_ok=True)
            shutil.rmtree(dest)
        for k, v in files.items():
            if k.startswith(f"claude/{n}/"):
                p = skills_dir / k[len("claude/"):]
                p.parent.mkdir(parents=True, exist_ok=True)
                p.write_bytes(v)
        print(f"installed {dest}")
    for key, dest in (("AGENTS.md", home / ".codex" / "AGENTS.md"),
                      ("GEMINI.md", home / ".gemini" / "GEMINI.md")):
        dest.parent.mkdir(parents=True, exist_ok=True)
        if dest.exists() and "GENERATED by 08_Platform_Builds" not in dest.read_text(
                encoding="utf-8", errors="ignore"):
            shutil.copy2(dest, dest.with_name(f"{dest.stem}.bak_{stamp}{dest.suffix}"))
            print(f"backed up existing {dest}")
        dest.write_bytes(files[key])
        print(f"installed {dest}")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--install", action="store_true")
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--lint", action="store_true")
    a = ap.parse_args(argv)
    cfg = yaml.safe_load((ROOT / "library.yaml").read_text(encoding="utf-8"))
    files, errs, warns, index = build_files(cfg)
    for w in warns:
        print(f"warning: {w}")
    for e in errs:
        print(f"error: {e}")
    if errs:
        return 1
    if a.lint:
        return 0
    man = manifest_for(files)

    if a.check:
        cur = current_out()
        problems = []
        for k in sorted(set(cur) | set(files)):
            if k not in files:
                problems.append(f"out/{k} is not produced by the masters (hand-added?)")
            elif k not in cur:
                problems.append(f"out/{k} missing (run build.py)")
            elif cur[k] != files[k]:
                problems.append(f"out/{k} differs from masters (hand-edited or stale)")
        if not MANIFEST.exists() or MANIFEST.read_text(encoding="utf-8") != man:
            problems.append("manifest.json stale (run build.py)")
        if not update_readme(index, write=False):
            problems.append("README.md index stale (run build.py)")
        for p in problems:
            print(p)
        return 1 if problems else 0

    if OUT.exists():
        for p in OUT.iterdir():
            if p.name == ".gitkeep":
                continue
            shutil.rmtree(p) if p.is_dir() else p.unlink()
    OUT.mkdir(exist_ok=True)
    for k, v in files.items():
        p = OUT / k
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(v)
    MANIFEST.write_text(man, encoding="utf-8", newline="\n")
    update_readme(index, write=True)
    print(f"built {len(files)} files into {OUT}")
    if a.install:
        install(files, a.force)
    return 0


if __name__ == "__main__":
    sys.exit(main())
