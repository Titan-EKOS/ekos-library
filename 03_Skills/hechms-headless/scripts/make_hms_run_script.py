#!/usr/bin/env python3
"""
make_hms_run_script.py - write a Jython compute script and a .cmd launcher for a
headless HEC-HMS 4.13 run (HEC-HMS.cmd -s <script>).

The generated Jython script is Python 2 syntax (HMS bundles Jython 2.7). It opens
the project, computes each run inside its own try/except so one failed case does
not stop the rest, writes one status line per run, and shuts the engine down.
The .cmd launcher runs it from the HMS install folder, sends console output to a
log, and writes a .done file at the end so a chained step can wait on it.

Console text is NOT the success test: every -s run prints a harmless JAXB
"Premature end of file" exception. Run check_hms_results.py afterwards.

Usage (EKOS, venv python by full path):
  "%HYDRO_PY%" make_hms_run_script.py ^
      --project-file "D:\\Jobs\\<job>\\20_Working\\HMS\\Model_413\\Model.hms" ^
      --runs "EX 100yr 3hr" "EX 100yr 24hr" ^
      --out-dir "D:\\Jobs\\<job>\\20_Working\\HMS\\_run" ^
      --hms-dir "C:\\Program Files\\HEC\\HEC-HMS\\4.13"

  --runs-file <txt> (one run name per line) may replace --runs.
  --api legacy writes the older JythonHms form (OpenProject / Compute / Exit).
"""
import argparse
import os
import sys

PROJECT_API = r'''# Generated by make_hms_run_script.py - HEC-HMS 4.13 Jython (Python 2 syntax)
from hms.model import Project
from hms import Hms
import time

PROJECT_FILE = r"%(project_file)s"
STATUS_FILE = r"%(status_file)s"
RUNS = %(runs)r

status = open(STATUS_FILE, "w")
status.write("run|result|seconds|message\n")
project = Project.open(PROJECT_FILE)
for run in RUNS:
    t0 = time.time()
    try:
        project.computeRun(run)
        status.write("%%s|COMPUTED|%%.1f|\n" %% (run, time.time() - t0))
    except Exception as e:
        status.write("%%s|FAILED|%%.1f|%%s\n" %% (run, time.time() - t0, str(e).replace("|", "/")))
    status.flush()
project.close()
status.close()
Hms.shutdownEngine()
'''

LEGACY_API = r'''# Generated by make_hms_run_script.py - HEC-HMS JythonHms (legacy form)
from hms.model.JythonHms import *
import time

STATUS_FILE = r"%(status_file)s"
RUNS = %(runs)r

status = open(STATUS_FILE, "w")
status.write("run|result|seconds|message\n")
OpenProject(r"%(project_name)s", r"%(project_dir)s")
for run in RUNS:
    t0 = time.time()
    try:
        Compute(run)
        status.write("%%s|COMPUTED|%%.1f|\n" %% (run, time.time() - t0))
    except Exception as e:
        status.write("%%s|FAILED|%%.1f|%%s\n" %% (run, time.time() - t0, str(e).replace("|", "/")))
    status.flush()
status.close()
Exit(1)
'''

CMD = r'''@echo off
rem Generated by make_hms_run_script.py
if exist "%(done_file)s" del "%(done_file)s"
pushd "%(hms_dir)s"
call HEC-HMS.cmd -s "%(script_file)s" > "%(log_file)s" 2>&1
set RC=%%ERRORLEVEL%%
popd
echo exit_code=%%RC%% > "%(done_file)s"
'''


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--project-file", required=True, help="full path to the .hms file (an upgraded 4.13 working copy)")
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--runs", nargs="+", help="run names exactly as in the .run file")
    g.add_argument("--runs-file", help="text file, one run name per line")
    ap.add_argument("--out-dir", required=True, help="folder for script, launcher, log, status and .done files")
    ap.add_argument("--hms-dir", default=r"C:\Program Files\HEC\HEC-HMS\4.13", help="HEC-HMS install folder")
    ap.add_argument("--tag", default="compute", help="file name stem for the generated files")
    ap.add_argument("--api", choices=["project", "legacy"], default="project")
    a = ap.parse_args()

    if a.runs_file:
        with open(a.runs_file, encoding="utf-8") as fh:
            runs = [ln.strip() for ln in fh if ln.strip() and not ln.lstrip().startswith("#")]
    else:
        runs = a.runs
    if not runs:
        sys.exit("no runs given")

    win = lambda p: p.replace("/", "\\")
    project_file = win(a.project_file)
    if not project_file.lower().endswith(".hms"):
        sys.exit("--project-file must point to the .hms file")
    project_dir, hms_name = project_file.rsplit("\\", 1) if "\\" in project_file else ("", project_file)
    project_name = hms_name[:-4]

    out_dir = a.out_dir
    os.makedirs(out_dir, exist_ok=True)
    out_win = win(os.path.abspath(out_dir)) if os.name == "nt" else win(out_dir)
    names = {
        "script_file": out_win + "\\" + a.tag + "_hms.py",
        "status_file": out_win + "\\" + a.tag + "_status.txt",
        "log_file": out_win + "\\" + a.tag + "_console.log",
        "done_file": out_win + "\\" + a.tag + ".done",
    }
    values = dict(names, project_file=project_file, project_dir=project_dir, project_name=project_name,
                  runs=list(runs), hms_dir=win(a.hms_dir))
    jy = (PROJECT_API if a.api == "project" else LEGACY_API) % values
    cmd = CMD % values

    jy_path = os.path.join(out_dir, a.tag + "_hms.py")
    cmd_path = os.path.join(out_dir, "run_" + a.tag + ".cmd")
    with open(jy_path, "w", newline="\r\n", encoding="utf-8") as fh:
        fh.write(jy)
    with open(cmd_path, "w", newline="\r\n", encoding="utf-8") as fh:
        fh.write(cmd)
    print("WROTE", jy_path)
    print("WROTE", cmd_path)
    print("RUNS ", len(runs), "->", "; ".join(runs))
    print("NEXT  run the .cmd, wait for", names["done_file"], "then run check_hms_results.py")


if __name__ == "__main__":
    main()
